#!/usr/bin/env bash
set -euo pipefail

# Lists every `static func testX()` in Tests/RecallTests so new tests run without
# being registered by hand.

OUTPUT="build/generated/TestRegistry.swift"
mkdir -p "$(dirname "${OUTPUT}")"

{
    echo "// Generated by scripts/generate_test_registry.sh. Do not edit."
    echo "enum TestRegistry {"
    echo "    static let all: [(name: String, run: () throws -> Void)] = ["
    for file in $(find Tests/RecallTests -name '*.swift' | sort); do
        awk '
            /^(struct|enum) [A-Za-z0-9_]+Tests/ {
                suite = $2
                sub(/[^A-Za-z0-9_].*/, "", suite)
                label = suite
                sub(/Tests$/, "", label)
            }
            /static func test[A-Za-z0-9_]*\(\)/ {
                match($0, /test[A-Za-z0-9_]*/)
                name = substr($0, RSTART, RLENGTH)
                printf "        (\"%s.%s\", %s.%s),\n", label, name, suite, name
            }
        ' "${file}"
    done
    echo "    ]"
    echo "}"
} >"${OUTPUT}"
